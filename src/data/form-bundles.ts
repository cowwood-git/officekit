export const FORM_BUNDLES: readonly FormBundle[] = [...CORE_BUNDLES, ...EXTRA_BUNDLES];

export function getBundle(slug: string): FormBundle | undefined {
  return FORM_BUNDLES.find((bundle) => bundle.slug === slug);
}

export function bundlesForForm(slug: string): readonly FormBundle[] {
  return FORM_BUNDLES.filter((bundle) => bundle.steps.some((step) => step.slug === slug));
}

export function bundleForms(bundle: FormBundle): readonly FormTemplate[] {
  return bundle.steps
    .map((step) => getForm(step.slug))
    .filter((form): form is FormTemplate => Boolean(form));
}

export function nextStep(
  bundle: FormBundle,
  slug: string,
): { step: FormBundleStep; index: number } | undefined {
  const index = bundle.steps.findIndex((step) => step.slug === slug);
  if (index < 0) return undefined;
  const step = bundle.steps[index + 1];
  return step ? { step, index: index + 1 } : undefined;
}
